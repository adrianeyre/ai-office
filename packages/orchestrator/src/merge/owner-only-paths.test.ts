import type { PullRequestFile } from "@ai-office/github";
import { describe, expect, it } from "vitest";

import {
  changedLines,
  generatedRules,
  heldBackByFloor,
  isLockfile,
  markedGenerated,
  matchesOwnerOnlyPath,
  ownerOnlyPathChanged,
} from "./owner-only-paths.ts";

// Owner-only Paths and the changed-lines limit (Scorecards PRD, FR-122 to
// FR-125): plain rules on the paths a pull request changes and how many
// lines it changes.

const file = (
  path: string,
  changes: Partial<PullRequestFile> = {},
): PullRequestFile => ({
  path,
  status: "modified",
  patch: null,
  additions: 1,
  deletions: 0,
  ...changes,
});

describe("matching an Owner-only Path", () => {
  it("matches at any depth under a ** glob, and only from the top of the repository", () => {
    expect(matchesOwnerOnlyPath("src/auth/**", "src/auth/session.ts")).toBe(
      true,
    );
    expect(
      matchesOwnerOnlyPath("src/auth/**", "src/auth/tokens/refresh/jwt.ts"),
    ).toBe(true);
    expect(matchesOwnerOnlyPath("src/auth/**", "lib/src/auth/session.ts")).toBe(
      false,
    );
    expect(matchesOwnerOnlyPath("src/auth/**", "src/authors.ts")).toBe(false);
    // One `*` is one level; `**/` is any.
    expect(matchesOwnerOnlyPath("src/*.ts", "src/index.ts")).toBe(true);
    expect(matchesOwnerOnlyPath("src/*.ts", "src/auth/index.ts")).toBe(false);
    expect(matchesOwnerOnlyPath("**/*.sql", "db/migrations/0001.sql")).toBe(
      true,
    );
    expect(matchesOwnerOnlyPath("*.sql", "db/migrations/0001.sql")).toBe(false);
    expect(matchesOwnerOnlyPath("*.sql", "schema.sql")).toBe(true);
  });

  it("matches whatever the case of the glob and the path", () => {
    expect(matchesOwnerOnlyPath("src/auth/**", "SRC/Auth/Session.ts")).toBe(
      true,
    );
    expect(matchesOwnerOnlyPath("Migrations/**", "migrations/0001.sql")).toBe(
      true,
    );
  });

  it("reads braces, ?, a leading ./ or /, and matches nothing for an empty glob", () => {
    expect(matchesOwnerOnlyPath("{infra,deploy}/**", "deploy/prod.tf")).toBe(
      true,
    );
    expect(matchesOwnerOnlyPath("v?.json", "v1.json")).toBe(true);
    expect(matchesOwnerOnlyPath("./src/auth/**", "src/auth/a.ts")).toBe(true);
    expect(matchesOwnerOnlyPath("/src/auth/**", "src/auth/a.ts")).toBe(true);
    expect(matchesOwnerOnlyPath("  ", "src/auth/a.ts")).toBe(false);
  });

  it("counts a renamed file's old path, so moving a file out is held back too", () => {
    const moved = file("src/session.ts", {
      status: "renamed",
      previousPath: "src/auth/session.ts",
    });
    expect(ownerOnlyPathChanged([moved], ["src/auth/**"])).toEqual({
      path: "src/auth/session.ts",
      pattern: "src/auth/**",
      more: 0,
    });
    expect(ownerOnlyPathChanged([moved], ["lib/**"])).toBeUndefined();
  });

  it("names the first file matched, the glob that matched it, and how many more", () => {
    expect(
      ownerOnlyPathChanged(
        [
          file("README.md"),
          file("src/auth/a.ts"),
          file("migrations/0002.sql"),
          file("src/auth/b.ts"),
        ],
        ["migrations/**", "src/auth/**"],
      ),
    ).toEqual({ path: "src/auth/a.ts", pattern: "src/auth/**", more: 2 });
  });
});

describe("counting changed lines", () => {
  it("adds lines added and lines removed", () => {
    expect(
      changedLines([
        file("a.ts", { additions: 10, deletions: 4 }),
        file("b.ts", { additions: 0, deletions: 7 }),
      ]),
    ).toBe(21);
  });

  it("leaves out well-known lockfiles, wherever they are and whatever their case", () => {
    for (const path of [
      "pnpm-lock.yaml",
      "web/package-lock.json",
      "yarn.lock",
      "Cargo.lock",
      "poetry.lock",
      "Gemfile.lock",
      "go.sum",
    ]) {
      expect({ path, lockfile: isLockfile(path) }).toEqual({
        path,
        lockfile: true,
      });
    }
    expect(isLockfile("src/lock.ts")).toBe(false);
    expect(
      changedLines([
        file("src/a.ts", { additions: 3, deletions: 1 }),
        file("pnpm-lock.yaml", { additions: 900, deletions: 400 }),
        file("crates/core/Cargo.lock", { additions: 50, deletions: 0 }),
      ]),
    ).toBe(4);
  });

  it("leaves out files the base branch's .gitattributes marks linguist-generated", () => {
    const rules = generatedRules(
      [
        "# Generated by the API client generator",
        "src/generated/** linguist-generated",
        "*.pb.go linguist-generated=true",
        "src/generated/handwritten.ts -linguist-generated",
        "docs/ linguist-documentation",
        "",
      ].join("\n"),
    );
    const generated = (path: string) => markedGenerated(rules, path);
    expect(generated("src/generated/client.ts")).toBe(true);
    expect(generated("api/v1/service.pb.go")).toBe(true);
    expect(generated("src/generated/handwritten.ts")).toBe(false);
    expect(generated("docs/index.md")).toBe(false);
    expect(
      changedLines(
        [
          file("src/generated/client.ts", { additions: 2000, deletions: 0 }),
          file("api/v1/service.pb.go", { additions: 300, deletions: 10 }),
          file("src/generated/handwritten.ts", { additions: 5, deletions: 2 }),
        ],
        generated,
      ),
    ).toBe(7);
  });

  it("reads a folder pattern ending in a slash, and the last rule that matches", () => {
    const rules = generatedRules(
      "vendor/ linguist-generated\nvendor/ours/** linguist-generated=false\n",
    );
    expect(markedGenerated(rules, "vendor/lib/a.js")).toBe(true);
    expect(markedGenerated(rules, "app/vendor/lib/a.js")).toBe(true);
    expect(markedGenerated(rules, "vendor/ours/b.js")).toBe(false);
  });

  it("counts from the patch a file listed without counts", () => {
    expect(
      changedLines([
        {
          path: "a.ts",
          status: "modified",
          patch: "@@ -1,2 +1,2 @@\n-old\n+new\n+more\n unchanged",
        },
      ]),
    ).toBe(3);
  });
});

describe("why a Floor's rules hold a pull request back", () => {
  it("says nothing when the Floor sets neither", () => {
    expect(
      heldBackByFloor([file("src/auth/session.ts", { additions: 10_000 })], {
        ownerOnlyPaths: [],
        changedLinesLimit: null,
      }),
    ).toEqual([]);
  });

  it("names the file and the Owner-only Path, and the lines over the limit, as the Notice reads", () => {
    expect(
      heldBackByFloor(
        [
          file("src/auth/session.ts", { additions: 700, deletions: 100 }),
          file("src/auth/tokens.ts", { additions: 12, deletions: 0 }),
        ],
        { ownerOnlyPaths: ["src/auth/**"], changedLinesLimit: 500 },
      ),
    ).toEqual([
      "it changes `src/auth/session.ts` and 1 more file, an Owner-only Path (`src/auth/**`)",
      "it changes 812 lines, over the Floor's limit of 500",
    ]);
  });

  it("lets a pull request at the limit through", () => {
    expect(
      heldBackByFloor([file("a.ts", { additions: 400, deletions: 100 })], {
        ownerOnlyPaths: [],
        changedLinesLimit: 500,
      }),
    ).toEqual([]);
  });
});
