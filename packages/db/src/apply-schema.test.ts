import { readFile } from "node:fs/promises";

import { eq, sql } from "drizzle-orm";
import { describe, expect, it } from "vitest";

import {
  applySchema,
  schemaFile,
  schemaHash,
  schemaHashKey,
  SchemaMismatchError,
} from "./apply-schema.ts";
import { roles, schemaMeta } from "./schema.ts";
import { postgresTest } from "./testing/postgres.ts";

describe("schema.sql", () => {
  it("says it is generated, and how", async () => {
    const text = await readFile(schemaFile, "utf8");
    expect(text.startsWith("-- Generated by `pnpm db:generate`")).toBe(true);
  });

  it("is plain SQL, with no drizzle-kit statement breakpoints", async () => {
    const text = await readFile(schemaFile, "utf8");
    expect(text).not.toContain("statement-breakpoint");
  });
});

describe("the schema against Postgres 18", () => {
  postgresTest("is applied to a fresh Postgres 18", async ({ database }) => {
    const result = await database.db.execute<{ server_version_num: string }>(
      sql`SHOW server_version_num`,
    );
    expect(result.rows[0]?.server_version_num).toMatch(/^18\d{4}$/);
  });

  postgresTest(
    "creates schema_meta, recording the application and the schema's hash",
    async ({ database }) => {
      const rows = await database.db
        .select({ key: schemaMeta.key, value: schemaMeta.value })
        .from(schemaMeta)
        .orderBy(schemaMeta.key);
      const hash = schemaHash(await readFile(schemaFile, "utf8"));
      expect(rows).toEqual([
        { key: "application", value: "ai-office" },
        { key: schemaHashKey, value: hash },
      ]);
    },
  );

  postgresTest(
    "seeds the Role library's built-in Roles",
    async ({ database }) => {
      const rows = await database.db
        .select({ id: roles.id, stage: roles.stage })
        .from(roles)
        .orderBy(roles.id);
      expect(rows).toEqual([
        { id: "coder", stage: "work" },
        { id: "designer", stage: "work" },
        { id: "docs", stage: "docs" },
        { id: "qa", stage: "qa" },
        { id: "reviewer", stage: "review" },
      ]);
    },
  );

  postgresTest("is a no-op when applied again", async ({ database }) => {
    await applySchema(database.db);
    await applySchema(database.db);
    const rows = await database.db.select().from(schemaMeta);
    expect(rows).toHaveLength(2);
    const roleRows = await database.db.select().from(roles);
    expect(roleRows).toHaveLength(5);
  });

  postgresTest(
    "refuses a database made from a different schema, saying to recreate it",
    async ({ database }) => {
      const different = `${await readFile(schemaFile, "utf8")}\n-- changed\n`;
      const applying = applySchema(database.db, { schemaSql: different });
      await expect(applying).rejects.toBeInstanceOf(SchemaMismatchError);
      await expect(applying).rejects.toThrow(/pnpm db:reset/);
      // Nothing was changed.
      const [row] = await database.db
        .select({ value: schemaMeta.value })
        .from(schemaMeta)
        .where(eq(schemaMeta.key, schemaHashKey));
      expect(row?.value).toBe(schemaHash(await readFile(schemaFile, "utf8")));
    },
  );

  postgresTest(
    "refuses a database with schema_meta but no recorded hash",
    async ({ database }) => {
      await database.db
        .delete(schemaMeta)
        .where(eq(schemaMeta.key, schemaHashKey));
      await expect(applySchema(database.db)).rejects.toThrow(
        /no schema hash recorded.*pnpm db:reset/,
      );
    },
  );

  // These two run in order: the second must not see the first one's row.
  postgresTest(
    "hand each test its own database (write)",
    async ({ database }) => {
      await database.db
        .insert(schemaMeta)
        .values({ key: "written-by", value: "a previous test" });
    },
  );

  postgresTest(
    "hand each test its own database (read)",
    async ({ database }) => {
      const rows = await database.db
        .select()
        .from(schemaMeta)
        .where(eq(schemaMeta.key, "written-by"));
      expect(rows).toEqual([]);
    },
  );
});
