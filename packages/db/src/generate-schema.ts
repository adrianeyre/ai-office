// `pnpm db:generate`: writes the whole schema as one plain SQL file,
// `schema.sql`, from `src/schema.ts` (with `drizzle-kit export`) and the SQL
// it cannot say (`src/schema-extras.sql`). AI Office is not in production
// yet, so there are no migrations: after a change, recreate the development
// database (`pnpm db:reset`).
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { schemaFile } from "./apply-schema.ts";

const packageFolder = fileURLToPath(new URL("..", import.meta.url));

const header = `-- Generated by \`pnpm db:generate\` (packages/db/src/generate-schema.ts)
-- from src/schema.ts (\`drizzle-kit export\`) and src/schema-extras.sql.
-- Do not edit it by hand: change those and run \`pnpm db:generate\` again.
-- \`pnpm db:schema\` applies it to an empty database; after a change,
-- recreate the database with \`pnpm db:reset\` (this deletes its data).
`;

const tables = execFileSync("pnpm", ["exec", "drizzle-kit", "export"], {
  cwd: packageFolder,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
});
const extras = await readFile(
  new URL("schema-extras.sql", import.meta.url),
  "utf8",
);
await writeFile(
  schemaFile,
  `${header}\n${tables.trimEnd()}\n\n${extras.trimEnd()}\n`,
);
