/**
 * Reading the log newest first, a page at a time, filtered and within a
 * time range (the Activity Feed), against whatever store `bus` has. The
 * bus's clock must put each event a second after the one before, from
 * 12:00:00 on 8 October 2026.
 */
export async function checkHistory(bus: EventBus): Promise<void> {
  for (const [index, event] of [
    exampleEvents["floor.created"],
    exampleEvents["agent.status_changed"],
    exampleEvents["sign_in.failed"],
    exampleEvents.handoff,
    exampleEvents["sign_in.succeeded"],
    exampleEvents["issue.label_changed"],
  ].entries()) {
    const stored = await bus.publish(event);
    expect(stored.id).toBe(index + 1);
  }
  const ids = async (query: EventHistoryQuery) =>
    (await bus.history(query)).map(({ id }) => id);

  expect(await ids({})).toEqual([6, 5, 4, 3, 2, 1]);
  // A page, then the page after it.
  expect(await ids({ limit: 4 })).toEqual([6, 5, 4, 3]);
  expect(await ids({ limit: 4, beforeId: 3 })).toEqual([2, 1]);
  // Filtered by Floor, Agent, issue and type, as the stream is.
  expect(await ids({ filter: { floorId: "web-shop" } })).toEqual([6, 4, 2, 1]);
  expect(await ids({ filter: { agentId: "grace" } })).toEqual([4]);
  expect(await ids({ filter: { issue: 4 } })).toEqual([6, 4, 2]);
  expect(
    await ids({ filter: { types: ["sign_in.failed", "sign_in.succeeded"] } }),
  ).toEqual([5, 3]);
  // From (inclusive) and to (exclusive).
  const at = (seconds: number) =>
    new Date(Date.UTC(2026, 9, 8, 12, 0, seconds));
  expect(await ids({ from: at(2), to: at(5) })).toEqual([5, 4, 3]);
  expect(await ids({ from: at(4), filter: { floorId: "web-shop" } })).toEqual([
    6,
  ]);
  const [newest] = await bus.history({ limit: 1 });
  expect(newest?.occurredAt).toEqual(at(5));
  expect(newest?.event).toEqual(exampleEvents["issue.label_changed"]);
}
